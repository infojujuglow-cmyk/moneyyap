import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const analyticsSource = await readFile('src/services/analytics.ts', 'utf8');
const comparisonSource = await readFile('src/services/report-comparisons.ts', 'utf8');
const compile = (source) => ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const analyticsModule = { exports: {} };
new Function('exports', 'module', 'require', compile(analyticsSource))(analyticsModule.exports, analyticsModule, () => ({}));
const comparisonModule = { exports: {} };
new Function('exports', 'module', 'require', compile(comparisonSource))(comparisonModule.exports, comparisonModule, () => analyticsModule.exports);
const { monthWindow, yearWindow, periodSummary, monthlyYearTrend, yearMonthWithinWindow, compareCategories, change } = comparisonModule.exports;
const now = new Date(2026, 10, 6, 12);
const entry = (id, year, month, day, amount, type = 'expense', categoryId = 'groceries') => ({ id, type, financialEffect: type === 'income' || type === 'refund' ? 'income' : type === 'transfer' || type === 'credit_card_payment' ? 'internal_transfer' : 'expense', businessClassification: 'operating', categoryId, amount, transactionDate: new Date(year, month, day, 12).toISOString() });
const transactions = [entry('sep', 2025, 8, 10, 15000), entry('oct', 2026, 9, 10, 20000), entry('nov', 2026, 10, 4, 1000), entry('salary', 2026, 10, 5, 5000, 'income', 'salary'), entry('refund', 2026, 10, 5, 200, 'refund'), entry('transfer', 2026, 10, 5, 500, 'transfer'), entry('card', 2026, 10, 5, 300, 'credit_card_payment'), entry('future', 2026, 11, 10, 4000)];
assert.equal(periodSummary(transactions, monthWindow(2026, 10, now)).spending, 800);
assert.equal(periodSummary(transactions, monthWindow(2025, 8, now)).spending, 15000);
assert.equal(periodSummary(transactions, monthWindow(2026, 9, now)).spending, 20000);
assert.equal(periodSummary(transactions, yearWindow(2026, now)).spending, 20800);
assert.equal(periodSummary(transactions, yearWindow(2025, now)).spending, 15000);
const firstYtd = yearWindow(2025, now, true), secondYtd = yearWindow(2026, now, true);
assert.deepEqual([firstYtd.end.getMonth(), firstYtd.end.getDate(), secondYtd.end.getMonth(), secondYtd.end.getDate()], [10, 6, 10, 6]);
assert.equal(change(20000, 15000).percentage, 33.33333333333333);
assert.equal(change(200, 0).percentage, null);
const trend = monthlyYearTrend(transactions, 2026, now);
assert.equal(trend.length, 12);
assert.equal(trend[10].partial, true);
assert.equal(trend[11].future, true);
assert.equal(trend[11].transactionCount, 0);
assert.equal(yearMonthWithinWindow(transactions, 2026, 11, yearWindow(2026, now).end), null);
assert.equal(yearMonthWithinWindow(transactions, 2026, 10, yearWindow(2026, now).end).spending, 800);
const categories = [{ id: 'food', name: 'Food', type: 'expense', parentId: null }, { id: 'groceries', name: 'Groceries', type: 'expense', parentId: 'food' }, { id: 'salary', name: 'Salary', type: 'income', parentId: null }];
const rows = compareCategories(transactions.slice(0, 1), transactions.slice(1, 2), categories, 'expense');
assert.deepEqual([rows[0].before, rows[0].after, rows[0].children[0].before, rows[0].children[0].after], [15000, 20000, 15000, 20000]);
assert.deepEqual(rows[0].transactionIds, ['sep', 'oct']);
console.log('report comparisons: months, years, YTD, future months, categories, transfers, refunds, and zero baselines passed');
