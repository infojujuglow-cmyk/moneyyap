import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile('src/services/scheduled.ts','utf8');
const compiled = ts.transpileModule(source,{ compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022} }).outputText;
const module = { exports:{} };
new Function('exports','module','require',compiled)(module.exports,module,() => ({}));
const { occurrenceDate, projectedOccurrences, projectedTotals, projectedAccountCashFlow, todayInTimezone, noonInTimezone } = module.exports;
const rule = (starts_on,frequency,anchor_day=null,last_day_of_month=false) => ({starts_on,frequency,anchor_day,last_day_of_month});
assert.deepEqual([1,2,3,4].map((n) => occurrenceDate(rule('2028-01-31','monthly',31),n)),['2028-01-31','2028-02-29','2028-03-31','2028-04-30']);
assert.deepEqual([1,2,3].map((n) => occurrenceDate(rule('2027-01-31','monthly',31),n)),['2027-01-31','2027-02-28','2027-03-31']);
assert.deepEqual([1,2,3].map((n) => occurrenceDate(rule('2027-04-30','monthly',30,true),n)),['2027-04-30','2027-05-31','2027-06-30']);
assert.equal(occurrenceDate(rule('2028-02-29','yearly',29),2),'2029-02-28');
assert.equal(occurrenceDate(rule('2026-11-06','daily'),3),'2026-11-08');
assert.equal(occurrenceDate(rule('2026-11-06','weekly'),3),'2026-11-20');
assert.equal(occurrenceDate(rule('2026-11-06','biweekly'),3),'2026-12-04');
assert.equal(occurrenceDate(rule('2026-11-06','quarterly',6),2),'2027-02-06');
assert.equal(occurrenceDate(rule('2026-11-06','semiannual',6),2),'2027-05-06');
assert.equal(occurrenceDate(rule('2026-11-06','once'),2),null);
assert.equal(todayInTimezone('Asia/Manila',new Date('2026-11-05T17:00:00Z')),'2026-11-06');
assert.equal(noonInTimezone('2026-11-06','Asia/Manila'),'2026-11-06T04:00:00.000Z');
assert.equal(noonInTimezone('2026-07-01','America/Los_Angeles'),'2026-07-01T19:00:00.000Z');
const schedule = {id:'s1',starts_on:'2026-11-06',frequency:'weekly',anchor_day:6,last_day_of_month:false,ends_on:null,max_occurrences:3,status:'active',type:'expense',amount:500};
const occurrences = [{id:'o1',schedule_id:'s1',occurrence_number:1,due_on:'2026-11-06',status:'recorded',amount_override:null},{id:'o2',schedule_id:'s1',occurrence_number:2,due_on:'2026-11-13',status:'skipped',amount_override:null}];
const projected = projectedOccurrences(schedule,occurrences,'2026-12-31');
assert.equal(projected.length,3);
assert.deepEqual(projected.map((item) => item.status),['recorded','skipped','pending']);
assert.deepEqual(projectedOccurrences({...schedule,next_occurrence_number:3},occurrences,'2026-12-31').map((item) => item.number),[1,2,3]);
assert.deepEqual(projectedOccurrences({...schedule,next_occurrence_number:3},occurrences.slice(0,1),'2026-12-31').map((item) => item.number),[1,3]);
assert.equal(projectedTotals(projected,'2026-11-01','2026-12-31').expenses,500);
const transfer = {...schedule,id:'t1',type:'transfer',amount:1000,max_occurrences:1};
assert.deepEqual(projectedTotals(projected.concat(projectedOccurrences(transfer,[],'2026-12-31')),'2026-11-01','2026-12-31'),{expenses:500,income:0});
assert.deepEqual(projectedAccountCashFlow(projectedOccurrences({...transfer,account_from_id:'bank',account_to_id:'cash'},[],'2026-12-31'),'bank','2026-11-01','2026-12-31'),{outgoing:1000,incoming:0});
console.log('scheduled transactions: all frequencies, leap years, month end, timezone, statuses, and transfer exclusions passed');
